import { appendFile, mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join, parse, resolve } from "node:path";

/** Where skills live, in scan order: the first copy of a name wins, and project folders come first. */
const PROJECT_DIRS = ["skills", ".agents/skills", ".claude/skills", ".codex/skills", ".opencode/skills", ".gemini/skills"];
const GLOBAL_DIRS = [".claude/skills", ".codex/skills", ".config/opencode/skills", ".gemini/config/skills", ".agents/skills"];
const PROJECT_MARKERS = [".git", ".factory", ...PROJECT_DIRS];
export const INDEX_PATH = ".factory/skills.md";

export interface SkillRow {
  name: string;
  description: string;
  scope: "project" | "global";
  path: string;
}

export interface IndexResult {
  project: boolean;
  path?: string;
  count: number;
  changed: boolean;
  duplicates: string[];
}

const exists = (p: string) =>
  stat(p).then(
    () => true,
    () => false,
  );

function frontmatter(text: string): Record<string, string> {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  const out: Record<string, string> = {};
  for (const line of m?.[1]?.split(/\r?\n/) ?? []) {
    const kv = /^([A-Za-z_-]+):\s*(.*)$/.exec(line);
    if (kv) out[kv[1]!] = kv[2]!.trim().replace(/^"(.*)"$/, "$1");
  }
  return out;
}

async function scan(dir: string, scope: SkillRow["scope"]): Promise<SkillRow[]> {
  const rows: SkillRow[] = [];
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  for (const e of entries.filter((x) => x.isDirectory() && !x.name.startsWith("_")).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(dir, e.name, "SKILL.md");
    const text = await readFile(path, "utf8").catch(() => undefined);
    if (!text) continue;
    const meta = frontmatter(text);
    rows.push({ name: meta.name || e.name, description: (meta.description ?? "").replace(/\|/g, "\\|"), scope, path: path.replace(/\\/g, "/") });
  }
  return rows;
}

/**
 * Writes `.factory/skills.md`: every installed skill once (project copies first), with its trigger text, scope and
 * exact path, so a main session can hand subagents exact skill files. Rewrites only when the content changed.
 */
export async function indexSkills(cwd: string, options: { home?: string; noGitignore?: boolean } = {}): Promise<IndexResult> {
  const home = resolve(options.home ?? homedir());
  const root = resolve(cwd);
  if (root === home || root === parse(root).root) return { project: false, count: 0, changed: false, duplicates: [] };
  let isProject = false;
  for (const marker of PROJECT_MARKERS) if (await exists(join(root, marker))) isProject = true;
  if (!isProject) return { project: false, count: 0, changed: false, duplicates: [] };

  const found: SkillRow[] = [];
  for (const d of PROJECT_DIRS) found.push(...(await scan(join(root, d), "project")));
  for (const d of GLOBAL_DIRS) found.push(...(await scan(join(home, d), "global")));
  const seen = new Map<string, SkillRow>();
  const duplicates = new Set<string>();
  for (const row of found) {
    if (seen.has(row.name)) duplicates.add(row.name);
    else seen.set(row.name, row);
  }
  const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
  const content = [
    "# Skill index",
    "",
    "Generated by `factory skills index`. Read the exact SKILL.md before using a skill; never summarize it for a subagent.",
    "",
    "| Skill | Trigger and purpose | Scope | Path |",
    "|-------|---------------------|-------|------|",
    ...rows.map((r) => `| ${r.name} | ${r.description} | ${r.scope} | ${r.path} |`),
    "",
  ].join("\n");

  const path = join(root, INDEX_PATH);
  const changed = (await readFile(path, "utf8").catch(() => undefined)) !== content;
  if (changed) {
    await mkdir(join(root, ".factory"), { recursive: true });
    await writeFile(path, content);
  }
  if (!options.noGitignore) await ignoreIndex(root);
  return { project: true, path, count: rows.length, changed, duplicates: [...duplicates].sort() };
}

async function ignoreIndex(root: string): Promise<void> {
  const file = join(root, ".gitignore");
  const text = await readFile(file, "utf8").catch(() => undefined);
  if (text === undefined || text.split(/\r?\n/).some((l) => l.trim() === INDEX_PATH || l.trim() === ".factory/" || l.trim() === ".factory")) return;
  await appendFile(file, `${text.endsWith("\n") || !text ? "" : "\n"}${INDEX_PATH}\n`);
}
